CREATE OR ALTER VIEW dbo.VW_IMPORTADOR_INTENTOS_RECUPERADOS
AS
SELECT
    ok.ID_INTENTO AS ID_INTENTO_OK,
    ok.ID_RECEPCION,
    ok.CORRELACION_ORIGEN,
    ok.FECHA_FIN_UTC AS FIN_OK_UTC,
    prev.ID_INTENTO AS ID_INTENTO_PREVIO,
    prev.RESULTADO AS RESULTADO_PREVIO,
    prev.MENSAJE AS MENSAJE_PREVIO,
    prev.FECHA_FIN_UTC AS FIN_PREVIO_UTC
FROM dbo.IMPORTADOR_INTENTO ok
INNER JOIN dbo.IMPORTADOR_INTENTO prev
    ON prev.CORRELACION_ORIGEN = ok.CORRELACION_ORIGEN
   AND prev.FECHA_INICIO_UTC < ok.FECHA_INICIO_UTC
   AND prev.RESULTADO IN ('ERROR_SQL', 'SQL_NO_DISPONIBLE', 'INCIERTO')
WHERE ok.RESULTADO IN ('IMPORTADO', 'IMPORTADO_CON_ADVERTENCIAS');
GO

CREATE OR ALTER VIEW dbo.VW_IMPORTADOR_CONFLICTOS
AS
SELECT
    r.ID_RECEPCION,
    r.ID_TICKET,
    r.ID_RECEPCION_ORIGINAL,
    r.NOMBRE_FICHERO,
    r.RUTA_ORIGEN,
    r.HASH_SHA256,
    r.HASH_TICKET_ASOCIADO,
    r.TIENDA_FICHERO,
    r.TPV_FICHERO,
    r.FECHA_PROCESADO,
    r.NUM_FACTURA_FICHERO
FROM dbo.TICKET_RECEPCION r
WHERE r.ESTADO = 'CONFLICTO_MISMA_FACTURA';
GO

CREATE OR ALTER VIEW dbo.VW_IMPORTADOR_ARCHIVADO_PENDIENTE
AS
SELECT
    r.ID_RECEPCION,
    r.ESTADO,
    r.ESTADO_ARCHIVO,
    r.RUTA_ORIGEN,
    r.RUTA_DESTINO_PREVISTA,
    r.RUTA_FINAL,
    r.FECHA_ULTIMO_INTENTO,
    r.FECHA_PROCESADO
FROM dbo.TICKET_RECEPCION r
WHERE r.ESTADO_ARCHIVO IN ('ARCHIVANDO', 'ERROR_ARCHIVO')
   OR (
        r.ESTADO_ARCHIVO = 'PENDIENTE'
        AND r.ESTADO IN ('PROCESADO', 'PROCESADO_CON_ADVERTENCIAS', 'DUPLICADO', 'CONFLICTO_MISMA_FACTURA', 'ERROR_XML', 'ERROR_PERMANENTE')
      );
GO

CREATE OR ALTER VIEW dbo.VW_IMPORTADOR_RENDIMIENTO_HORA
AS
SELECT
    DATEADD(HOUR, DATEDIFF(HOUR, CONVERT(datetime2(3), '2000-01-01'), i.FECHA_FIN_UTC), CONVERT(datetime2(3), '2000-01-01')) AS HORA_UTC,
    COUNT(*) AS INTENTOS_CERRADOS,
    SUM(CASE WHEN i.RESULTADO IN ('IMPORTADO', 'IMPORTADO_CON_ADVERTENCIAS') THEN 1 ELSE 0 END) AS IMPORTACIONES_NUEVAS,
    AVG(i.DURACION_MS) AS DURACION_MEDIA_MS,
    MAX(i.DURACION_MS) AS DURACION_MAX_MS
FROM dbo.IMPORTADOR_INTENTO i
WHERE i.FECHA_FIN_UTC IS NOT NULL
  AND i.DURACION_MS IS NOT NULL
GROUP BY DATEADD(HOUR, DATEDIFF(HOUR, CONVERT(datetime2(3), '2000-01-01'), i.FECHA_FIN_UTC), CONVERT(datetime2(3), '2000-01-01'));
GO
